/*
=================
Sys_SigHandler
=================
*/
void Sys_SigHandler( int signal )
{
	static bool signalcaught = false;

	if( signalcaught )
	{
		fprintf( stderr, "DOUBLE SIGNAL FAULT: Received signal %d, exiting...\n",
			signal );
	}
	else
	{
		signalcaught = true;
		CL_Shutdown();
		SV_Shutdown(va("Received signal %d", signal) );
	}

	if( signal == SIGTERM || signal == SIGINT )
		Sys_Exit( 1 );
	else
		Sys_Exit( 2 );
}

